# Install Intel Low Power Mode Daemon for supported hybrid Intel CPUs (Alder Lake and newer)
# Supported models: Alder Lake (151/154), Raptor Lake (183/186/191),
# Meteor Lake (170/172), Lunar Lake (189), Panther Lake (204)

# intel-lpmd 0.1.0's shipped intel_lpmd_config_F6_M204.xml leaves <Mode> inside
# an XML comment, sets BalancedDef/PowersaverDef to -1 (DEFAULT_OFF), and maps
# 4P8E4L-25W UTIL_IDLE to ActiveCPUs 16-19 on a 16-CPU (0-15) topology with no
# SMT. Write a TDP-specific override (_T<tdp>.xml), which intel_lpmd loads
# ahead of the package-owned F6_M204.xml, using the live LP-E core range.
_omarchy_write_ptl_lpmd_config() {
  local powercap_path="${OMARCHY_POWERCAP_PATH:-/sys/class/powercap}"
  local cpu_atom_path="${OMARCHY_CPU_ATOM_PATH:-/sys/devices/cpu_atom/cpus}"
  local cpu_sysfs_path="${OMARCHY_CPU_SYSFS_PATH:-/sys/devices/system/cpu}"
  local lpmd_conf_dir="${OMARCHY_LPMD_CONF_DIR:-/etc/intel_lpmd}"
  local marker="<!-- Generated by Omarchy for Intel Panther Lake (F6_M204) -->"

  local rapl_dir name max_uw tdp=0
  for rapl_dir in "$powercap_path"/intel-rapl*; do
    [[ -r $rapl_dir/name && -r $rapl_dir/constraint_0_max_power_uw ]] || continue
    name=$(<"$rapl_dir/name")
    [[ $name == package* ]] || continue
    max_uw=$(<"$rapl_dir/constraint_0_max_power_uw")
    if [[ $max_uw =~ ^[0-9]+$ ]] && ((max_uw >= 1000000)); then
      tdp=$((max_uw / 1000000))
      break
    fi
  done
  ((tdp > 0)) || return 0

  [[ -r $cpu_atom_path && -r $cpu_sysfs_path/present ]] || return 0
  local atom_spec all_cpus
  atom_spec=$(<"$cpu_atom_path")
  all_cpus=$(<"$cpu_sysfs_path/present")
  [[ -n $atom_spec && -n $all_cpus ]] || return 0

  # Mirror intel_lpmd's is_cpu_lcore(): Atom cores without an L3 cache.
  local part start end cpu
  local -a lcore_ids=()
  IFS=',' read -ra parts <<<"$atom_spec"
  for part in "${parts[@]}"; do
    if [[ $part =~ ^([0-9]+)-([0-9]+)$ ]]; then
      start=${BASH_REMATCH[1]}
      end=${BASH_REMATCH[2]}
    elif [[ $part =~ ^[0-9]+$ ]]; then
      start=$part
      end=$part
    else
      continue
    fi
    for ((cpu = start; cpu <= end; cpu++)); do
      if [[ -d $cpu_sysfs_path/cpu$cpu && ! -d $cpu_sysfs_path/cpu$cpu/cache/index3 ]]; then
        lcore_ids+=("$cpu")
      fi
    done
  done
  ((${#lcore_ids[@]} > 0)) || return 0

  local lcores="" range_start="" range_end=""
  for cpu in "${lcore_ids[@]}"; do
    if [[ -z $range_start ]]; then
      range_start=$cpu
      range_end=$cpu
    elif ((cpu == range_end + 1)); then
      range_end=$cpu
    else
      if ((range_start == range_end)); then
        lcores+="${lcores:+,}$range_start"
      else
        lcores+="${lcores:+,}$range_start-$range_end"
      fi
      range_start=$cpu
      range_end=$cpu
    fi
  done
  if ((range_start == range_end)); then
    lcores+="${lcores:+,}$range_start"
  else
    lcores+="${lcores:+,}$range_start-$range_end"
  fi

  local conf_file="$lpmd_conf_dir/intel_lpmd_config_F6_M204_T${tdp}.xml"
  if [[ -f $conf_file ]] && ! grep -qF "$marker" "$conf_file" 2>/dev/null; then
    return 0
  fi

  local xml
  read -r -d '' xml <<EOF || true
<?xml version="1.0"?>
$marker
<Configuration>
  <lp_mode_cpus></lp_mode_cpus>
  <lp_mode_epp></lp_mode_epp>
  <Mode>0</Mode>
  <PerformanceDef>-1</PerformanceDef>
  <BalancedDef>0</BalancedDef>
  <PowersaverDef>0</PowersaverDef>
  <HfiLpmEnable>0</HfiLpmEnable>
  <WLTHintEnable>1</WLTHintEnable>
  <WLTHintPollEnable>0</WLTHintPollEnable>
  <WLTHintMask>15</WLTHintMask>
  <HfiSuvEnable>0</HfiSuvEnable>
  <IgnoreITMT>0</IgnoreITMT>
  <BalancedSliderAC>1</BalancedSliderAC>
  <BalancedSliderDC>3</BalancedSliderDC>
  <SliderOffsetAC>0</SliderOffsetAC>
  <SliderOffsetDC>3</SliderOffsetDC>
  <States>
    <CPUFamily> 6 </CPUFamily>
    <CPUModel> 204 </CPUModel>
    <CPUConfig> * </CPUConfig>
    <State>
      <ID> 1 </ID>
      <Name> UTIL_IDLE </Name>
      <WLTType> 1 </WLTType>
      <ActiveCPUs>${lcores}</ActiveCPUs>
    </State>
    <State>
      <ID> 2 </ID>
      <Name> UTIL_IDLE_SUSTAIN </Name>
      <WLTType> 2 </WLTType>
      <ActiveCPUs>${all_cpus}</ActiveCPUs>
    </State>
    <State>
      <ID> 3 </ID>
      <Name> UTIL_IDLE_BURSTY </Name>
      <WLTType> 3 </WLTType>
      <ActiveCPUs>${all_cpus}</ActiveCPUs>
    </State>
  </States>
</Configuration>
EOF

  if ((EUID == 0)) || [[ -n ${OMARCHY_LPMD_CONF_DIR:-} ]]; then
    install -d -m 755 "$lpmd_conf_dir"
    printf '%s\n' "$xml" >"$conf_file"
    chmod 644 "$conf_file"
  else
    sudo install -d -m 755 "$lpmd_conf_dir"
    printf '%s\n' "$xml" | sudo tee "$conf_file" >/dev/null
    sudo chmod 644 "$conf_file"
  fi
}

if omarchy-hw-intel && omarchy-battery-present; then
  cpu_model=$(grep -m1 "^model\s*:" "${OMARCHY_CPUINFO_PATH:-/proc/cpuinfo}" 2>/dev/null | cut -d: -f2 | tr -d ' ')
  if [[ $cpu_model =~ ^(151|154|170|172|183|186|189|191|204)$ ]]; then
    if [[ -n ${OMARCHY_PKG_QUEUE_FILE:-} && -n ${OMARCHY_SERVICE_QUEUE_FILE:-} ]]; then
      OMARCHY_PKG_DEFER=1 omarchy-pkg-add intel-lpmd
      printf '%s\n' intel_lpmd.service >>"$OMARCHY_SERVICE_QUEUE_FILE"
    else
      omarchy-pkg-add intel-lpmd
      if ((EUID == 0)); then
        systemctl enable intel_lpmd.service
      else
        sudo systemctl enable intel_lpmd.service
      fi
    fi

    if ((cpu_model == 204)); then
      _omarchy_write_ptl_lpmd_config
    fi
  fi
fi

unset -f _omarchy_write_ptl_lpmd_config
