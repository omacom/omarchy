# Detect T2 MacBook models using PCI IDs
# Vendor: 106b (Apple), Device IDs: 1801 or 1802 (T2 Security Chip)
if lspci -nn | grep "106b:180[12]" >/dev/null; then
  echo "Detected MacBook with T2 chip. Installing support items..."

  # apple-bcm-firmware-fetcher reads its firmware off an on-disk macOS volume —
  # Wi-Fi firmware for T2 Macs is only legally obtainable from there. A
  # single-boot install that wiped macOS has no such volume, so the fetch comes
  # up empty; those machines need the firmware supplied from a macOS copy or a
  # downloaded recovery image instead.
  omarchy-pkg-add \
    linux-t2 \
    linux-t2-headers \
    apple-t2-audio-config \
    apple-bcm-firmware-fetcher \
    t2fanrd

  # Enable T2 fan control
  systemctl enable t2fanrd.service

  mkdir -p /etc/modules-load.d
  {
    echo "t2bce_vhci"
    echo "hci_bcm4377"
  } > /etc/modules-load.d/t2.conf

  # linux-t2 7.1.4 replaced the apple-bce driver with t2bce; t2bce_vhci is the
  # virtual USB host controller the internal keyboard hangs off, and mkinitcpio
  # pulls t2bce_core/t2bce_dma in via module dependencies.
  mkdir -p /etc/mkinitcpio.conf.d
  echo "MODULES+=(t2bce_vhci usbhid hid_apple hid_generic xhci_pci xhci_hcd)" > \
    /etc/mkinitcpio.conf.d/apple-t2.conf

  mkdir -p /etc/limine-entry-tool.d
  cat > /etc/limine-entry-tool.d/t2-mac.conf <<'EOF'
# Generated by Omarchy installer for T2 Mac support
KERNEL_CMDLINE[default]+=" intel_iommu=on iommu=pt pm_async=off mem_sleep_default=deep"
EOF

  # t2fanrd only reads sections for detected fans, so Fan2 is harmless on
  # single-fan models and required on dual-fan MacBooks.
  cat > /etc/t2fand.conf <<'EOF'
[Fan1]
low_temp=55
high_temp=75
speed_curve=linear
always_full_speed=false

[Fan2]
low_temp=55
high_temp=75
speed_curve=linear
always_full_speed=false
EOF

  # Apple T2 Internal Keyboard / Trackpad
  #
  # The T2 internal trackpad uses the Magic Trackpad 2 architecture (hid-magicmouse)
  # bridged over USB via t2bce_vhci. libinput's fallback [Apple Touchpads USB] rule
  # sets AttrTouchSizeRange=150:130 (calibrated for older bcm5974 hardware). Because the
  # Magic Trackpad reports touch contact sizes of 10-20, libinput 1.32+ discards
  # touch and motion events as noise while clicks continue to pass.
  #
  # Override AttrTouchSizeRange to 20:10 matching the Apple Magic Trackpad v2 quirks.
  mkdir -p /etc/libinput
  touch /etc/libinput/local-overrides.quirks
  if ! grep -q '\[Apple Internal Magic Trackpad (T2)\]' /etc/libinput/local-overrides.quirks; then
    cat >> /etc/libinput/local-overrides.quirks <<'EOF'

[Apple Internal Magic Trackpad (T2)]
MatchUdevType=touchpad
MatchVendor=0x05AC
MatchName=*Apple Internal Keyboard / Trackpad*
AttrTouchSizeRange=20:10
AttrPalmPressureThreshold=190
AttrPalmSizeThreshold=900
AttrThumbSizeThreshold=800
EOF
  fi
fi
