# Name the platform drivers a Snapdragon laptop needs before its disk, keyboard and panel work.

mkinitcpio_dir=${OMARCHY_QUALCOMM_MKINITCPIO_DIR:-/etc/mkinitcpio.conf.d}
initcpio_install_dir=${OMARCHY_QUALCOMM_INITCPIO_INSTALL_DIR:-/etc/initcpio/install}

if omarchy-hw-aarch64-qualcomm; then
  # Snapdragon firmware reaches its EFI variables through the QSEECOM driver,
  # which loads from the real root, so the initramfs's efivarfs mount fails and
  # prints "fsopen() failed: Operation not supported" on every boot. The real
  # root mounts efivarfs again. Quiet that one mount in the image's copy of
  # init_functions until mkinitcpio does it upstream.
  mkdir -p "$initcpio_install_dir"
  cat >"$initcpio_install_dir/omarchy-quiet-efivars" <<'HOOK'
#!/bin/bash

build() {
  local init_functions="$BUILDROOT/init_functions"

  [[ -f $init_functions ]] || return 0
  sed -i 's|^\([[:space:]]*mount -t efivarfs efivarfs /sys/firmware/efi/efivars -o nosuid,nodev,noexec\)$|\1 2>/dev/null|' "$init_functions"
}

help() {
  cat <<HELP
Quiets the initramfs efivarfs mount, which fails on Snapdragon laptops until
their EFI variable driver loads from the real root.
HELP
}
HOOK


  mkdir -p "$mkinitcpio_dir"
  cat >"$mkinitcpio_dir/qualcomm-platform.conf" <<'CONF'
# Generated by Omarchy for Qualcomm Snapdragon devices.
# Pin control, interconnect, PMIC and bus drivers of the X1 and X2 (Glymur)
# chips. Arch Linux ARM's kernel builds them in. A kernel that builds them as
# modules needs them named here, since mkinitcpio's hooks only pick storage,
# input and display drivers. The ? skips one that a kernel does not have.
MODULES+=(pinctrl-x1e80100? qnoc-x1e80100? pinctrl-glymur? qnoc-glymur?
  spmi-pmic-arb? pinctrl-spmi-gpio? i2c-qcom-geni?
  reset-gpio? gpio-shared-proxy? qcom_hwspinlock? smem? smp2p? socinfo? nvmem_qfprom?
  nvmem_qcom-spmi-sdam? qcom-cpucp-mbox? pci-pwrctrl-pwrseq? pwrseq-qcom-wcn? dwc3-qcom?
  rtc-pm8xxx? qcom-pon? pm8941-pwrkey? icc-bwmon? qcom_tsens? qcom-spmi-temp-alarm?)

# Runs after base, which adds the init_functions it quiets.
HOOKS+=(omarchy-quiet-efivars)
CONF
fi
