# Install packaged Qualcomm firmware and vendor-signed blobs extracted from Windows.
# Keep the DSP driver disabled when starting it could disconnect the root disk.

if omarchy-hw-aarch64-qualcomm; then
  omarchy-pkg-add linux-firmware-qcom qcom-firmware-extract

  qcom-firmware-extract --install --no-rebuild || true

  modprobe_dir=${OMARCHY_QUALCOMM_MODPROBE_DIR:-/etc/modprobe.d}
  sysfs=${OMARCHY_QUALCOMM_SYSFS:-/sys}
  root_source=$(findmnt -no SOURCE --nofsroot / 2>/dev/null || true)

  # Starting the DSPs resets the USB-C controllers, which drops a root disk on
  # one of them. The multiport controller behind the USB-A ports stays up.
  root_on_usb_c=false
  if [[ -n $root_source ]]; then
    while read -r disk transport; do
      if [[ $transport == "usb" && $root_on_usb_c == "false" ]]; then
        # A USB disk counts as USB-C unless its controller is the multiport one.
        root_on_usb_c=true
        dir=$(readlink -f "$sysfs/class/block/$disk" || true)
        while [[ -n $dir ]]; do
          compatible=""
          if [[ -r $dir/of_node/compatible ]]; then
            compatible=" $(tr '\0' ' ' <"$dir/of_node/compatible") "
          fi
          if [[ $compatible == *dwc3* ]]; then
            if [[ $compatible == *"-dwc3-mp "* ]]; then
              root_on_usb_c=false
            fi
            dir=""
          else
            dir=${dir%/*}
          fi
        done
      fi
    done < <(lsblk -snro NAME,TRAN "$root_source" 2>/dev/null)
  fi

  mkdir -p "$modprobe_dir"
  if [[ $root_on_usb_c == "true" ]]; then
    cat >"$modprobe_dir/qualcomm-adsp-nofw.conf" <<'CONF'
# Generated by Omarchy for Qualcomm Snapdragon devices.
# Keep the DSP driver off while the root disk is attached over USB-C.
blacklist qcom_q6v5_pas
CONF
  elif ! missing_firmware=$(qcom-firmware-extract --list-missing) || grep -q 'adsp' <<<"$missing_firmware"; then
    cat >"$modprobe_dir/qualcomm-adsp-nofw.conf" <<'CONF'
# Generated by Omarchy for Qualcomm Snapdragon devices.
# Keep the DSP driver off until its signed firmware can be verified.
blacklist qcom_q6v5_pas
CONF
  else
    rm -f "$modprobe_dir/qualcomm-adsp-nofw.conf"
  fi
fi
