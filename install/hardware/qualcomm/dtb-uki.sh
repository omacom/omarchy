# Embed Qualcomm device trees so systemd-stub can select one from SMBIOS data.
# DeviceTreeAuto requires literal paths, so hardware setup refreshes the list.

if omarchy-hw-aarch64-qualcomm; then
  omarchy-pkg-add systemd-ukify

  # Arch Linux ARM's kernel keeps every board's device trees in /boot/dtbs.
  # Omarchy's own kernel keeps its Snapdragon ones under its package name, and
  # those come first, so the trees match the kernel that boots.
  dtb_root=${OMARCHY_QUALCOMM_DTB_ROOT:-/boot/dtbs}
  dtb_dir=$dtb_root/qcom
  for kernel_dtb_dir in "$dtb_root"/linux-omarchy*/qcom; do
    if [[ -d $kernel_dtb_dir ]]; then
      dtb_dir=$kernel_dtb_dir
      break
    fi
  done
  dtb_dir=${OMARCHY_QUALCOMM_DTB_DIR:-$dtb_dir}
  uki_config=${OMARCHY_QUALCOMM_UKI_CONFIG:-/etc/kernel/uki.conf}
  dtbs=()
  for dtb in "$dtb_dir"/x1*.dtb "$dtb_dir"/hamoa*.dtb \
    "$dtb_dir"/glymur*.dtb "$dtb_dir"/sc8280xp*.dtb; do
    if [[ -f $dtb && $dtb != *-el2.dtb ]]; then
      dtbs+=("$dtb")
    fi
  done

  # An installed machine needs only the tree it runs on. The running device
  # tree's root compatible is that tree's byte for byte, so the one file that
  # holds the same list is it, and the UKI embeds just that tree, which also
  # needs no hardware IDs. Without a running device tree, or without exactly
  # one match, systemd-stub keeps choosing from every tree by SMBIOS data.
  # A tree file holds a property as its token, length and name offset, then
  # the value, so matching the length too takes only the whole property, never
  # a longer list that ends the same way. od writes each byte as " xx", which
  # keeps a match on byte boundaries and the newline bytes out of grep's way.
  own_dtb=""
  running_compatible=${OMARCHY_PROC_ROOT:-/proc}/device-tree/compatible
  if ((${#dtbs[@]} > 0)) && [[ -s $running_compatible ]]; then
    length=$(wc -c <"$running_compatible")
    pattern=$(printf ' 00 00 00 03 %02x %02x %02x %02x' $((length >> 24 & 255)) \
      $((length >> 16 & 255)) $((length >> 8 & 255)) $((length & 255)))
    pattern+="( [0-9a-f]{2}){4}$(od -An -v -tx1 "$running_compatible" | tr -d '\n')"
    matches=()
    for dtb in "${dtbs[@]}"; do
      if grep -qE "$pattern" <(od -An -v -tx1 "$dtb" | tr -d '\n'); then
        matches+=("$dtb")
      fi
    done
    if ((${#matches[@]} == 1)); then
      own_dtb=${matches[0]}
    fi
  fi

  if ((${#dtbs[@]} == 0)); then
    echo "No Windows-on-ARM device trees under $dtb_dir; the UKI gets no .dtbauto sections" >&2
  else
    managed_begin="# BEGIN OMARCHY QUALCOMM DEVICE TREES"
    managed_end="# END OMARCHY QUALCOMM DEVICE TREES"

    mkdir -p "$(dirname "$uki_config")"
    uki_tmp=$(mktemp "${uki_config}.XXXXXX")

    if [[ -f $uki_config ]]; then
      cp -p "$uki_config" "$uki_tmp"
      awk -v begin="$managed_begin" -v end="$managed_end" '
        $0 == begin { managed = 1; next }
        managed && $0 == end { managed = 0; next }
        !managed { print }
      ' "$uki_config" >"$uki_tmp"
    else
      chmod 0644 "$uki_tmp"
    fi

    {
      echo "$managed_begin"
      echo "# Generated by Omarchy for Qualcomm Snapdragon devices."
      if [[ -n $own_dtb ]]; then
        echo "# This machine's own device tree, matched by its running compatible."
        echo "[UKI]"
        echo "DeviceTree=$own_dtb"
      else
        echo "# systemd-stub selects a device tree from SMBIOS data."
        echo "# After a kernel update adds new boards, rerun 'omarchy apply hardware'"
        echo "# and rebuild the UKI with 'sudo limine-mkinitcpio'."
        echo "[UKI]"
        echo "DeviceTreeAuto=${dtbs[*]}"
      fi
      echo "$managed_end"
    } >>"$uki_tmp"

    if [[ -f $uki_config ]] && cmp -s "$uki_tmp" "$uki_config"; then
      rm -f "$uki_tmp"
    else
      mv -f "$uki_tmp" "$uki_config"
      # The UKI carries the trees once it is rebuilt. An image's first boot
      # rebuilds after its last step, but does not watch this file.
      if [[ -n ${OMARCHY_IMAGE_BOOT_REBUILD:-} ]]; then
        : >"$OMARCHY_IMAGE_BOOT_REBUILD"
      fi
    fi
    if [[ -n $own_dtb ]]; then
      echo "Embedded this machine's device tree, $own_dtb, in $uki_config"
    else
      echo "Listed ${#dtbs[@]} device trees in $uki_config"
    fi
  fi
fi
