#!/usr/bin/python3
"""Release-time rendering using the reviewed pinned companion's real renderer."""
import json
from pathlib import Path
import subprocess
import sys
import tempfile

source, output = map(Path, sys.argv[1:])
program = (source / 'apply.sh').read_text().split("<<'PY'\n", 1)[1].split('\nPY\n', 1)[0]
with tempfile.TemporaryDirectory() as directory:
    layout = Path(directory) / 'layout.json'
    data = json.loads((source / 'layout-animated.json').read_text())
    # No build-account UID or fontconfig leaks into a reusable system package.
    data['fontTemplate'] = 'monospace'
    layout.write_text(json.dumps(data))
    output.parent.mkdir(parents=True, exist_ok=True)
    arguments = [str(layout), str(Path(directory)/'missing-bindings'), '-- begin', '-- end',
                 'Generated by io.github.austindixson.touchbar', str(output), '65536', '262144']
    subprocess.run([sys.executable, '-', *arguments], input=program, text=True, check=True)
