#!/bin/bash
#
# The omarchy-thunderbolt mkinitcpio hook gives the image a udev rule for each
# Thunderbolt device boltd would authorize on its own, so a keyboard on a
# Thunderbolt 3 dock or display types at the disk unlock prompt. It reads Bolt's
# store as boltd does and leaves everything else to boltd.

set -euo pipefail

source "$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)/base-test.sh"

test_tmp=$(mktemp -d)
trap 'rm -rf "$test_tmp"' EXIT

hook="$ROOT/etc/initcpio/install/omarchy-thunderbolt"
store="$test_tmp/boltd"
rules="$test_tmp/root/usr/lib/udev/rules.d/70-omarchy-thunderbolt.rules"

display=c2010000-0072-741e-8393-1fe15e244809
dock=d6030000-0080-7708-2393-a2c9c0d0e101
manual=a1b2c3d4-0000-1111-2222-333344445555

new_store() {
  rm -rf "$store" "$test_tmp/root"
  mkdir -p "$store/devices" "$test_tmp/root"
}

# A device record as boltd writes it; $2 is the policy.
stored_device() {
  printf '[device]\nname=Device\nvendor=Vendor\ngeneration=3\ntype=peripheral\n\n[user]\npolicy=%s\nlabel=Device\nstoretime=1792833593\n' "$2" >"$store/devices/$1"
}

auth_mode() {
  printf '# Generated by boltd - do not edit\n[config]\nversion=1\nAuthMode=%s\n' "$1" >"$store/boltd.conf"
}

# Run the hook's build the way mkinitcpio runs it, with mkinitcpio's add_file
# when this machine has it and a stand-in that copies stdin otherwise.
run_hook() {
  (
    set +u
    BUILDROOT=$test_tmp/root
    OMARCHY_BOLT_STORE=$store
    if [[ -n ${functions:-} ]]; then
      source "$functions"
    else
      add_file() {
        [[ $1 == "-" && $3 == "644" ]] || return 1
        mkdir -p "$BUILDROOT/${2%/*}"
        cat >"$BUILDROOT/$2"
      }
    fi
    source "$hook"
    build
  ) >/dev/null
}

rule_for() {
  printf 'ACTION=="add", SUBSYSTEM=="thunderbolt", ATTR{unique_id}=="%s", ATTR{authorized}=="0", ATTRS{security}=="user"%s, ATTR{authorized}="1"\n' "$1" "${2:-}"
}
iommu=', ATTRS{iommu_dma_protection}=="1"'

assert_rules() {
  local description=$1 expected=$2 actual
  run_hook || fail "$description" "the hook's build failed"
  if [[ -z $expected ]]; then
    [[ ! -e $rules ]] || fail "$description" "rules: $(<"$rules")"
  else
    [[ -f $rules ]] || fail "$description" "no rules file in the image"
    actual=$(<"$rules")
    [[ $actual == "${expected%$'\n'}" ]] ||
      fail "$description" "expected:"$'\n'"$expected"$'\n'"actual:"$'\n'"$actual"
  fi
  pass "$description"
}

functions=""

new_store
stored_device "$display" iommu
assert_rules "an iommu device is authorized where the domain has IOMMU DMA protection" "$(rule_for "$display" "$iommu")"

new_store
stored_device "$dock" auto
assert_rules "an auto device is authorized at the user security level" "$(rule_for "$dock")"

new_store
stored_device "$manual" manual
assert_rules "a manual device waits for boltd" ""

new_store
stored_device "$dock" auto
stored_device "$display" iommu
stored_device "$manual" manual
assert_rules "only the devices boltd would authorize get a rule" "$(rule_for "$display" "$iommu")"$'\n'"$(rule_for "$dock")"

new_store
stored_device "$display" iommu
auth_mode disabled
assert_rules "Bolt's auth mode off authorizes nothing" ""

new_store
stored_device "$display" iommu
auth_mode enabled
assert_rules "Bolt's auth mode on authorizes as without a config" "$(rule_for "$display" "$iommu")"

rm -rf "$store" "$test_tmp/root"
mkdir -p "$test_tmp/root"
assert_rules "a machine without Bolt's store builds without a rule" ""

new_store
assert_rules "an empty store builds without a rule" ""

new_store
stored_device "$display" iommu
stored_device 'x", RUN+="sh' auto
assert_rules "a record not named by a UUID stays out of the rule" "$(rule_for "$display" "$iommu")"

if command -v udevadm >/dev/null; then
  new_store
  stored_device "$dock" auto
  stored_device "$display" iommu
  run_hook || fail "udev accepts the generated rules" "the hook's build failed"
  udevadm verify --no-style "$rules" >/dev/null || fail "udev accepts the generated rules" "$(udevadm verify --no-style "$rules" 2>&1)"
  pass "udev accepts the generated rules"
else
  skip "udev accepts the generated rules (no udevadm)"
fi

if [[ -r /usr/lib/initcpio/functions ]]; then
  functions=/usr/lib/initcpio/functions
  new_store
  stored_device "$display" iommu
  assert_rules "mkinitcpio's own add_file puts the rule in the image" "$(rule_for "$display" "$iommu")"
  [[ $(stat -c %a "$rules") == "644" ]] || fail "the rule in the image is mode 644" "mode: $(stat -c %a "$rules")"
  pass "the rule in the image is mode 644"
  functions=""
else
  skip "mkinitcpio's own add_file puts the rule in the image (no mkinitcpio)"
fi

# The drop-in joins whatever HOOKS line comes before it, including an
# omarchy_hooks.conf pacman kept from before the baseline, which sets HOOKS
# outright.
hooks=$(
  set +u
  HOOKS=()
  printf 'HOOKS=(base udev plymouth keyboard autodetect microcode modconf kms keymap consolefont block encrypt filesystems fsck)\n' >"$test_tmp/omarchy_hooks.conf"
  source "$test_tmp/omarchy_hooks.conf"
  source "$ROOT/etc/mkinitcpio.conf.d/thunderbolt_hook.conf"
  printf '%s' "${HOOKS[*]}"
)
[[ $hooks == "base udev plymouth keyboard autodetect microcode modconf kms keymap consolefont block encrypt filesystems fsck omarchy-thunderbolt" ]] ||
  fail "a kept omarchy_hooks.conf still gets the hook" "HOOKS=$hooks"
pass "a kept omarchy_hooks.conf still gets the hook"
