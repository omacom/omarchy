    def write(self, path, text):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        path.chmod(0o755)

    def stub(self, name, body):
        self.write(self.tools / name, '#!/bin/bash\n' + body + '\n')

    def copy(self, source, destination):
        text = source.read_text().replace('EUID', 'TEST_EUID')
        replacements = {
            '/usr/share/omarchy/shell/plugins/touchbar': str(self.plugin),
            '/usr/lib/omarchy-touchbar': str(self.lib),
            '/usr/share/omarchy-touchbar': str(self.work / 'share'),
            '/usr/share/omarchy/default/touchbar': str(self.main / 'default/touchbar'),
            '/etc/tiny-dfr': str(self.work / 'etc/tiny-dfr'),
            '/etc/systemd/system': str(self.work / 'etc/systemd/system'),
            '/run/systemd/system': str(self.work / 'systemd-live'),
            '/etc/tmpfiles.d': str(self.work / 'rules'),
        }
        for name in ('sudo', 'pkexec', 'pacman', 'id', 'omarchy-touchbar', 'systemctl', 'journalctl', 'getent', 'systemd-tmpfiles'):
            replacements['/usr/bin/' + name] = str(self.tools / name)
        for original, replacement in replacements.items():
            text = text.replace(original, replacement)
        self.write(destination, text)

    def run_command(self, command, *args, **overrides):
        environment = dict(self.env, **overrides)
        return subprocess.run([str(self.main / 'bin' / command), *args], env=environment,
                              capture_output=True, text=True, timeout=10)

    def events(self):
        path = self.work / 'events'
        return path.read_text() if path.exists() else ''

    def font_helper(self, destination):
        self.copy(ROOT / 'default/touchbar/setup-font-channel', destination)
        destination.write_text(destination.read_text().replace("runtime = Path('/run')", f"runtime = Path({str(self.work / 'run')!r})"))
        (self.work / 'rules').mkdir(exist_ok=True)
        (self.work / 'run').mkdir(exist_ok=True)
        self.stub('getent', 'exit 0')
        self.stub('systemd-tmpfiles', 'echo TMPFILES >> "$LOG"')
        return destination

    def font_rule(self, uid=None, gid=None, directory=True):
        uid = os.getuid() if uid is None else uid
        gid = os.getgid() if gid is None else gid
        rule = self.work / 'rules' / f'omarchy-touchbar-font-{uid}.conf'
        self.write(rule, f'd /run/omarchy-touchbar-font-{uid} 0755 {uid} {gid} -\n')
        rule.chmod(0o644)
        channel = self.work / 'run' / f'omarchy-touchbar-font-{uid}'
        if directory:
            channel.mkdir(mode=0o755)
            self.write(channel / 'current-font', 'monospace')
        return rule, channel

    def run_font(self, helper, *arguments):
        return subprocess.run([str(helper), *map(str, arguments)], env=dict(self.env, TEST_EUID='0'),
                              capture_output=True, text=True, timeout=10)

    def test_unsupported_all_phases_no_effects(self):
        def snapshot():
            return {str(p.relative_to(self.work)): hashlib.sha256(p.read_bytes()).hexdigest()
                    for p in self.work.rglob('*') if p.is_file()}
        before = snapshot()
        for command in ('omarchy-install-touchbar', 'omarchy-setup-touchbar-system', 'omarchy-setup-touchbar-user'):
            result = self.run_command(command, SUPPORTED='0')
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual(snapshot(), before)

    def test_privileged_helpers_protect_shell_startup(self):
        marker = self.work / 'startup-injection'
        injection = self.work / 'bash-env'
        self.write(injection, f'touch {marker}\n')
        font_helper = self.work / 'protected-font-channel'
        self.copy(ROOT / 'default/touchbar/setup-font-channel', font_helper)
        for helper in (self.lib / 'activate', font_helper):
            environment = dict(self.env, BASH_ENV=str(injection))
            result = subprocess.run([str(helper)], env=environment, capture_output=True, timeout=5)
            self.assertNotEqual(result.returncode, 0, 'non-root invocation must be refused')
            self.assertFalse(marker.exists(), 'protected startup sourced BASH_ENV')
            environment.pop('BASH_ENV')
            result = subprocess.run(['/usr/bin/bash', str(helper), '-p'], env=environment, capture_output=True, timeout=5)
            self.assertEqual(result.returncode, 126, 'decoy -p argument bypassed startup guard')

