#!/usr/bin/python3
"""Exercise real setup leaves/orchestrators with external OS/package boundaries.

Only absolute OS paths and the read-only EUID boundary are redirected in copied
scripts; installed commands expose no fixture/force mode. Packaged companion
entrypoints are external dependencies; their own suite validates rendering.
"""
import hashlib
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import tomllib
import unittest

ROOT = Path(sys.argv.pop(1))


class Setup(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.work = Path(self.temporary.name)
        self.main = self.work / 'main'
        self.tools = self.work / 'tools'
        self.home = self.work / 'home'
        self.lib = self.work / 'lib'
        self.plugin = self.main / 'shell/plugins/touchbar'
        for path in (self.main / 'bin', self.tools, self.home, self.lib, self.plugin / 'hooks', self.work / 'etc/tiny-dfr', self.work / 'share'):
            path.mkdir(parents=True)
        shutil.copytree(ROOT / 'config', self.main / 'config')
        for name in ('omarchy-install-touchbar', 'omarchy-setup-touchbar-system', 'omarchy-setup-touchbar-user',
                     'omarchy-shell-config', 'omarchy-hook-install', 'omarchy-plugin-validate'):
            self.copy(ROOT / 'bin' / name, self.main / 'bin' / name)
        self.copy(ROOT / 'scripts/touchbar-remove-bindings.py', self.main / 'scripts/touchbar-remove-bindings.py')
        self.copy(ROOT / 'packaging/omarchy-touchbar/activate', self.lib / 'activate')
        self.write(self.lib / 'hardware.py', 'import os,sys\nsys.exit(0 if os.environ["SUPPORTED"] == "1" else 1)\n')
        self.stub('omarchy-hw-touchbar', '[[ $SUPPORTED == 1 ]]')
        shutil.copy2(self.tools / 'omarchy-hw-touchbar', self.main / 'bin/omarchy-hw-touchbar')
        self.stub('omarchy-shell', 'echo "IPC $*" >> "$LOG"; exit 1')
        self.stub('sudo', '[[ ${1:-} != -- ]] || shift; TEST_EUID=0 "$@"')
        self.stub('pkexec', 'echo "ELEVATE $*" >> "$LOG"; TEST_EUID=0 "$@"')
        self.stub('id', 'case "$1" in -u) echo 2345 ;; -g) echo 2346 ;; -un) echo testowner ;; esac')
        self.stub('pacman', '''echo "PACMAN $*" >> "$LOG"
case "$1" in
  -Q) [[ $INSTALLED == 1 ]] && echo 'omarchy-touchbar 0.3.8.omarchy1-2' || exit 1 ;;
  -Qp) echo 'omarchy-touchbar 0.3.8.omarchy1-2' ;;
  -Si) [[ $PUBLISHED == 1 ]] ;;
  -S|-U) [[ $PACKAGE_FAIL == 0 ]] || exit 1; touch "$PAYLOAD_MARKER" ;;
esac''')
        self.stub('omarchy-touchbar', 'echo "NATIVE $*" >> "$LOG"; if [[ $1 == --capabilities ]]; then echo "trace-animation ttfx-wipe"; else [[ $CONFIG_FAIL == 0 ]]; fi')
        self.stub('systemctl', 'echo "SYSTEMCTL $*" >> "$LOG"; [[ $SERVICE_FAIL == 0 ]] || exit 1; [[ $1 != show ]] || echo invocation')
        self.stub('journalctl', 'echo startup')
        for compiler in ('makepkg', 'cargo', 'rustc', 'git'):
            self.stub(compiler, 'echo "FORBIDDEN compiler/source tool $0" >> "$LOG"; exit 127')
        self.write(self.lib / 'setup-font-channel', '#!/bin/bash\necho "FONT $*" >> "$LOG"\n')
        self.write(self.plugin / 'manifest.json', '{"schemaVersion":1,"id":"io.github.austindixson.touchbar","name":"Touch Bar","version":"1.4.0","author":"test","license":"MIT","description":"test","kinds":["service"],"entryPoints":{"service":"Service.qml"}}')
        self.write(self.plugin / 'Service.qml', 'import QtQuick\nItem {}\n')
        self.write(self.plugin / '.omarchy-touchbar-package', 'native=pinned\nplugin=pinned\n')
        self.write(self.plugin / 'hooks/90-touchbar-font', '#!/bin/bash\n# /usr/share/omarchy/shell/plugins/touchbar/sync-font.sh\n')
        self.write(self.plugin / 'enable-animation.sh', '#!/bin/bash\n[[ $OMARCHY_TOUCHBAR_SKIP_INSTALL == 1 ]] || exit 9\necho STAGE >> "$LOG"\n')
        self.write(self.plugin / 'apply.sh', '#!/bin/bash\necho APPLY >> "$LOG"\n')
        self.write(self.plugin / 'sync-font.sh', '#!/bin/bash\necho SYNC >> "$LOG"\n')
        self.write(self.work / 'share/default.toml', '# Generated by io.github.austindixson.touchbar\nFontTemplate = "monospace"\n')
        self.env = dict(os.environ, HOME=str(self.home), OMARCHY_PATH=str(self.main),
                        PATH=f'{self.main}/bin:{self.tools}:/usr/bin:/bin', TEST_EUID='1000',
                        LOG=str(self.work / 'events'), SUPPORTED='1', INSTALLED='1', PUBLISHED='1',
                        PACKAGE_FAIL='0', CONFIG_FAIL='0', SERVICE_FAIL='0',
                        OMARCHY_SETUP_CONTEXT='iso-chroot', PAYLOAD_MARKER=str(self.plugin / '.omarchy-touchbar-package'))
        for key in ('XDG_CONFIG_HOME', 'XDG_CACHE_HOME', 'XDG_DATA_HOME', 'XDG_STATE_HOME'):
            self.env.pop(key, None)

    def write(self, path, text):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        path.chmod(0o755)

    def stub(self, name, body):
        self.write(self.tools / name, '#!/bin/bash\n' + body + '\n')

    def copy(self, source, destination):
        text = source.read_text().replace('EUID', 'TEST_EUID')
        replacements = {
            '/usr/share/omarchy/shell/plugins/touchbar': str(self.plugin),
            '/usr/lib/omarchy-touchbar': str(self.lib),
            '/usr/share/omarchy-touchbar': str(self.work / 'share'),
            '/etc/tiny-dfr': str(self.work / 'etc/tiny-dfr'),
            '/etc/systemd/system': str(self.work / 'etc/systemd/system'),
            '/run/systemd/system': str(self.work / 'systemd-live'),
        }
        for name in ('sudo', 'pkexec', 'pacman', 'id', 'omarchy-touchbar', 'systemctl', 'journalctl'):
            replacements['/usr/bin/' + name] = str(self.tools / name)
        for original, replacement in replacements.items():
            text = text.replace(original, replacement)
        self.write(destination, text)

    def run_command(self, command, *args, **overrides):
        environment = dict(self.env, **overrides)
        return subprocess.run([str(self.main / 'bin' / command), *args], env=environment,
                              capture_output=True, text=True, timeout=10)

    def events(self):
        path = self.work / 'events'
        return path.read_text() if path.exists() else ''

    def test_unsupported_all_phases_no_effects(self):
        def snapshot():
            return {str(p.relative_to(self.work)): hashlib.sha256(p.read_bytes()).hexdigest()
                    for p in self.work.rglob('*') if p.is_file()}
        before = snapshot()
        for command in ('omarchy-install-touchbar', 'omarchy-setup-touchbar-system', 'omarchy-setup-touchbar-user'):
            result = self.run_command(command, SUPPORTED='0')
            self.assertEqual(result.returncode, 0, result.stderr)
            self.assertEqual(snapshot(), before)

    def test_privileged_helpers_protect_shell_startup(self):
        marker = self.work / 'startup-injection'
        injection = self.work / 'bash-env'
        self.write(injection, f'touch {marker}\n')
        font_helper = self.work / 'protected-font-channel'
        self.copy(ROOT / 'packaging/omarchy-touchbar/setup-font-channel', font_helper)
        for helper in (self.lib / 'activate', font_helper):
            environment = dict(self.env, BASH_ENV=str(injection))
            result = subprocess.run([str(helper)], env=environment, capture_output=True, timeout=5)
            self.assertNotEqual(result.returncode, 0, 'non-root invocation must be refused')
            self.assertFalse(marker.exists(), 'protected startup sourced BASH_ENV')
            environment.pop('BASH_ENV')
            result = subprocess.run(['/usr/bin/bash', str(helper), '-p'], env=environment, capture_output=True, timeout=5)
            self.assertEqual(result.returncode, 126, 'decoy -p argument bypassed startup guard')

    def test_preloaded_offline_owner_and_user_phases(self):
        result = self.run_command('omarchy-setup-touchbar-system', '--user', 'testowner', PUBLISHED='0')
        self.assertEqual(result.returncode, 0, result.stderr)
        config = tomllib.loads((self.work / 'etc/tiny-dfr/config.toml').read_text())
        self.assertEqual(config['FontSyncUid'], 2345)
        self.assertIn('FONT 2345 2346', self.events())
        self.assertNotIn('PACMAN -Si', self.events())
        self.assertNotIn('PACMAN -S ', self.events())
        self.assertNotIn('SYSTEMCTL', self.events())
        first = self.run_command('omarchy-setup-touchbar-user')
        self.assertEqual(first.returncode, 0, first.stderr)
        second = self.run_command('omarchy-setup-touchbar-user')
        self.assertEqual(second.returncode, 0, second.stderr)
        import json
        config = json.loads((self.home / '.config/omarchy/shell.json').read_text())
        self.assertEqual([p for p in config['plugins'] if p.get('id') == 'io.github.austindixson.touchbar'], [{'id':'io.github.austindixson.touchbar'}])
        self.assertNotIn('IPC', self.events())
        self.assertEqual(self.events().count('ELEVATE'), 1, 'offline user setup requested privileges')
        for forbidden in ('makepkg', 'cargo', 'rustc', 'git clone', 'base-devel'):
            self.assertNotIn(forbidden, self.events())

    def test_missing_published_package_and_package_failure(self):
        result = self.run_command('omarchy-install-touchbar', INSTALLED='0', PUBLISHED='0')
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('do not publish', result.stderr)
        self.assertFalse((self.home / '.config').exists())
        result = self.run_command('omarchy-install-touchbar', INSTALLED='0', PACKAGE_FAIL='1')
        self.assertNotEqual(result.returncode, 0)
        self.assertNotIn('STAGE', self.events())

    def test_explicit_prebuilt_archive(self):
        archive = self.work / 'reviewed.pkg.tar.zst'
        archive.write_text('package boundary fixture')
        result = self.run_command('omarchy-setup-touchbar-system', '--package', str(archive))
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn('PACMAN -U --noconfirm --ask 4 -- ' + str(archive), self.events())
        result = self.run_command('omarchy-setup-touchbar-system', '--package', 'relative.pkg.tar.zst')
        self.assertNotEqual(result.returncode, 0)

    def test_runtime_install_backup_uninstall_and_bindings(self):
        legacy = self.home / '.config/omarchy/plugins/io.github.austindixson.touchbar'
        legacy.mkdir(parents=True)
        shutil.copy(self.plugin / 'manifest.json', legacy / 'manifest.json')
        self.write(legacy / 'custom', 'keep old plugin')
        result = self.run_command('omarchy-install-touchbar')
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn('APPLY', self.events())
        backups = list(legacy.parent.glob('.touchbar-backup-*'))
        self.assertEqual(len(backups), 1)
        self.assertEqual((backups[0] / 'custom').read_text(), 'keep old plugin')
        bindings = self.home / '.config/hypr/bindings.lua'
        self.write(bindings, '-- own\n-- io.github.austindixson.touchbar begin\nmanaged\n-- io.github.austindixson.touchbar end\n-- after\n')
        result = self.run_command('omarchy-install-touchbar', '--uninstall', SUPPORTED='0')
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(bindings.read_text(), '-- own\n-- after\n')
        self.assertTrue(backups[0].exists())
        self.assertIn('tiny-dfr', self.events())
        self.assertFalse((self.work / 'etc/tiny-dfr/config.toml').exists())
        self.assertTrue(list((self.work / 'etc/tiny-dfr').glob('config.toml.omarchy-touchbar-backup-*')))

    def test_config_failure_rolls_back_without_user_mutation(self):
        result = self.run_command('omarchy-install-touchbar', CONFIG_FAIL='1')
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('restoring stock', result.stderr)
        self.assertIn('tiny-dfr', self.events())
        self.assertNotIn('STAGE', self.events())
        self.assertFalse((self.work / 'etc/tiny-dfr/config.toml').exists())

    def test_owner_registration_failure_stops_user_provisioning(self):
        # finalize_user is called under `if !` in real owner provisioning,
        # which suppresses errexit throughout the function. A failed root
        # registration must explicitly return before a successful runuser.
        program = (ROOT / 'bin/omarchy-provision-owner').read_text()
        function = 'finalize_user() {' + program.split('finalize_user() {', 1)[1].split('\n}', 1)[0] + '\n}'
        self.stub('getent', 'echo "testowner:x:2345:2346::${HOME}:/bin/bash"')
        self.stub('runuser', 'echo RUNUSER >> "$LOG"; exit 0')
        script = 'set -euo pipefail\nusername=testowner\nLOG_FILE=/dev/null\n' + function + '\nif ! finalize_user; then exit 77; fi\n'
        result = subprocess.run(['/usr/bin/bash', '-c', script],
                                env=dict(self.env, CONFIG_FAIL='1'),
                                capture_output=True, text=True, timeout=10)
        self.assertEqual(result.returncode, 77, result.stderr)
        self.assertNotIn('RUNUSER', self.events())

    def test_live_startup_failure_rolls_back(self):
        (self.work / 'systemd-live').mkdir()
        result = self.run_command('omarchy-setup-touchbar-system', SERVICE_FAIL='1')
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('restoring stock', result.stderr)
        self.assertIn('PACMAN -S --noconfirm --ask 4 -- tiny-dfr', self.events())
        self.assertFalse((self.work / 'etc/tiny-dfr/config.toml').exists())

    def test_failed_stock_transaction_restores_config(self):
        config = self.work / 'etc/tiny-dfr/config.toml'
        original = '# Omarchy Apple Silicon Touch Bar\nFontTemplate = "monospace"\n'
        self.write(config, original)
        result = self.run_command('omarchy-setup-touchbar-system', '--uninstall', PACKAGE_FAIL='1')
        self.assertNotEqual(result.returncode, 0)
        self.assertEqual(config.read_text(), original)

    def test_refuses_unrelated_plugin_and_unmanaged_config(self):
        legacy = self.home / '.config/omarchy/plugins/io.github.austindixson.touchbar'
        self.write(legacy / 'manifest.json', '{"id":"somebody.else"}')
        result = self.run_command('omarchy-setup-touchbar-user')
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('another plugin', result.stderr)
        self.write(self.work / 'etc/tiny-dfr/config.toml', '# administrator custom\n')
        result = self.run_command('omarchy-setup-touchbar-system')
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('Preserved custom', result.stderr)


unittest.main(verbosity=2)
